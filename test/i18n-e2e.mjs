// dc#58 다국어 틀: 기본 한국어(선택 숨김), ?lang=en/ja 미리 보기에서 아이템 이름이 그 언어, ?lang=ko로 끝
import { createRequire } from "node:module";
import fs from "node:fs"; import path from "node:path";
const require = createRequire(process.env.NODE_PATH + "/");
const { chromium } = require("playwright");
const REPO = process.argv[2], OUT = process.argv[3];
const I = createRequire(import.meta.url)(path.join(REPO, "items.js"));
const ORIGIN = "https://game.apacimtest.com/";
const results = []; const check = (n, ok, x = "") => { results.push(!!ok); console.log(`${ok ? "PASS" : "FAIL"} ${n}${x && !ok ? " — " + x : ""}`); };
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const find = (pred, pre) => { for (let i = 0; i < 200000; i++) { const it = I.generate(`${pre}|j10|k${i}`, "boss", 135); if (pred(it)) return it; } };
const leg = find(it => it.rarity === "legendary" && !it.set && I.itemElement(it) === "ice", "lg");
const uq = I.generateUnique("buy|m0123456789abcdef|robe", 175);
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || "/opt/pw-browsers/chromium-1194/chrome-linux/chrome" });
const ctx = await browser.newContext({ viewport: { width: 1100, height: 1000 } }); const page = await ctx.newPage(); const errors = [];
page.on("pageerror", e => errors.push(e.message));
await ctx.route(ORIGIN + "**", r => { const f = new URL(r.request().url()).pathname.slice(1) || "index.html";
  if (f === "ranking-config.js") return r.fulfill({ contentType: "text/javascript", body: `window.RANKING_API = "";` });
  const p = path.join(REPO, f); if (!fs.existsSync(p)) return r.fulfill({ status: 404, body: "" });
  r.fulfill({ contentType: f.endsWith(".js") ? "text/javascript" : "text/html", body: fs.readFileSync(p) }); });
await ctx.route("https://login.xsolla.com/**", r => r.fulfill({ status: 200, contentType: "application/json", body: "[]" }));
await ctx.addInitScript(([bag]) => { if (localStorage.getItem("seeded")) return; localStorage.setItem("seeded", 1);
  localStorage.setItem("rl_device_id", "i18ndev"); for (const k of ["rl_notice_v4", "rl_notice_75", "rl_notice_1019", "rl_notice_1023d", "rl_notice_1025a"]) localStorage.setItem(`${k}:g:i18ndev`, "1");
  localStorage.setItem("rl_inv:g:i18ndev", bag); }, [JSON.stringify({ bag: [leg, uq], equip: {}, log: [] })]);
const invText = async () => { await page.keyboard.press("i"); await sleep(400); const t = await page.locator("body").innerText(); await page.keyboard.press("Escape"); await sleep(200); return t; };

await page.goto(ORIGIN); await sleep(600);
check("default (Korean browser): Korean, language select shown on 🌐 자동", await page.evaluate(() => RLI18N.lang) === "ko" && await page.locator("#lang-select").isVisible() && await page.locator("#lang-select").inputValue() === "auto");
let t = await invText();
check("default: Korean item names", t.includes(I.itemName(leg)) && t.includes("고대 염라의 관복"), t.slice(0, 200));

await page.goto(ORIGIN + "?lang=en"); await sleep(600);
check("?lang=en: English preview, select visible", await page.evaluate(() => RLI18N.lang) === "en" && await page.locator("#lang-select").isVisible() && await page.evaluate(() => document.documentElement.lang) === "en");
t = await invText();
check("en: item names in English", t.includes("Legendary Hell") && t.includes("of Frost") && t.includes("Ancient Yeomra's Robe"), t.slice(0, 400));
check("en: shop rl_lang untouched", await page.evaluate(() => localStorage.getItem("rl_lang")) === null);
await page.goto(ORIGIN); await sleep(500);
check("preview stays for the tab without the parameter", await page.evaluate(() => RLI18N.lang) === "en");
await page.locator("#lang-select").selectOption("ja"); await page.waitForLoadState("load"); await sleep(600);
t = await invText();
check("select → ja: Japanese names", await page.evaluate(() => RLI18N.lang) === "ja" && t.includes("閻魔の官服") && t.includes("地獄の氷"), t.slice(0, 300));
await page.screenshot({ path: path.join(OUT, "i18n-ja.png") });
await page.locator("#lang-select").selectOption("ko"); await page.waitForLoadState("load"); await sleep(600);
check("select → ko (in preview): back to Korean, preview ends → 🌐 자동", await page.evaluate(() => RLI18N.lang) === "ko" && !(await page.evaluate(() => RLI18N.preview)) && await page.locator("#lang-select").inputValue() === "auto");
await page.goto(ORIGIN + "builds.html?lang=ja"); await sleep(800);
check("builds page loads in ja preview", await page.evaluate(() => RLI18N.lang) === "ja");
await page.goto(ORIGIN + "ranking.html?lang=en"); await sleep(800);
check("ranking page loads with i18n", await page.evaluate(() => typeof RLI18N) === "object");
check("no page errors", errors.length === 0, errors.join("; "));
await browser.close();
console.log(`\n${results.filter(Boolean).length}/${results.length} passed`);
